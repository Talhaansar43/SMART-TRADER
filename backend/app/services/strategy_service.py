"""Read-only baseline strategy evaluation with strict data provenance checks."""

import json
import logging
import math
from datetime import date, datetime, timezone
from typing import Any

logger = logging.getLogger(__name__)

FAST_WINDOW = 20
SLOW_WINDOW = 50
STRATEGY_NAME = "sma_crossover"
STRATEGY_VERSION = "1.0.0"
VERIFIED_HISTORY_SOURCES = {"finnhub", "yahoo_finance"}


def _finish_event(event: dict[str, Any]) -> dict[str, Any]:
    log_event = {key: value for key, value in event.items() if key != "priceHistory"}
    logger.info("Signal evaluation: %s", json.dumps(log_event, sort_keys=True))
    return event


def build_financial_kpis(
    metrics: dict[str, Any] | None,
    statements: dict[str, Any] | None,
    quote: dict[str, Any] | None,
) -> tuple[dict[str, float | None], dict[str, str | None]]:
    """Normalize provider metrics and derive KPIs only from available statements."""
    metrics = metrics if isinstance(metrics, dict) else {}
    statements = statements if isinstance(statements, dict) else {}
    quote = quote if isinstance(quote, dict) else {}

    def number(value: Any) -> float | None:
        if isinstance(value, (int, float)) and math.isfinite(value):
            return float(value)
        return None

    def metric(*keys: str) -> float | None:
        for key in keys:
            value = number(metrics.get(key))
            if value is not None:
                return value
        return None

    def statement_value(rows: Any, label: str) -> float | None:
        if not isinstance(rows, list):
            return None
        normalized_label = "".join(character for character in label.casefold() if character.isalnum())
        for row in rows:
            row_label = "".join(
                character for character in str(row.get("label", "")).casefold() if character.isalnum()
            ) if isinstance(row, dict) else ""
            if row_label == normalized_label:
                return number(row.get("value"))
        return None

    def statement_sum(rows: Any, labels: set[str]) -> float | None:
        if not isinstance(rows, list):
            return None
        values = [
            number(row.get("value"))
            for row in rows
            if isinstance(row, dict) and str(row.get("label", "")).casefold() in labels
        ]
        values = [value for value in values if value is not None]
        return sum(values) if values else None

    latest_balance = statements.get("latestBalanceSheet")
    latest_balance_rows = latest_balance.get("rows") if isinstance(latest_balance, dict) else None
    annual = statements.get("latestAnnual")
    annual_rows = annual.get("balanceSheet") if isinstance(annual, dict) else None
    income_rows = annual.get("incomeStatement") if isinstance(annual, dict) else None
    cash_flow_rows = annual.get("cashFlow") if isinstance(annual, dict) else None

    balance_debt = statement_sum(
        latest_balance_rows,
        {"term debt", "commercial paper"},
    )
    balance_cash = statement_sum(
        latest_balance_rows,
        {"cash and cash equivalents", "marketable securities"},
    )
    net_debt = balance_debt - balance_cash if balance_debt is not None and balance_cash is not None else None

    annual_assets = statement_value(annual_rows, "Total assets")
    annual_current_liabilities = statement_value(annual_rows, "Total current liabilities")
    annual_operating_income = statement_value(income_rows, "Operating income")
    annual_depreciation_amortization = statement_value(cash_flow_rows, "Depreciation and amortization")
    annual_ebitda = (
        annual_operating_income + annual_depreciation_amortization
        if annual_operating_income is not None and annual_depreciation_amortization is not None
        else None
    )
    capital_employed = (
        annual_assets - annual_current_liabilities
        if annual_assets is not None and annual_current_liabilities is not None
        else None
    )
    operating_cash_flow = statement_value(cash_flow_rows, "Cash generated by operating activities")
    capital_expenditure = statement_value(
        cash_flow_rows,
        "Payments for acquisition of property, plant and equipment",
    )
    free_cash_flow = (
        operating_cash_flow - capital_expenditure
        if operating_cash_flow is not None and capital_expenditure is not None
        else None
    )

    current_price = number(quote.get("currentPrice"))
    revenue_per_share = metric("revenuePerShareTTM")
    book_value_per_share = metric("bookValuePerShareQuarterly", "bookValuePerShareAnnual")
    return {
        "grossProfitMargin": metric("grossMarginTTM", "grossMarginAnnual"),
        "operatingProfitMargin": metric("operatingMarginTTM", "operatingMarginAnnual"),
        "netProfitMargin": metric("netProfitMarginTTM", "netProfitMarginAnnual"),
        "returnOnEquity": metric("roeTTM", "roeRfy"),
        "returnOnAssets": metric("roaTTM", "roaRfy"),
        "returnOnCapitalEmployed": (
            annual_operating_income / capital_employed * 100
            if annual_operating_income is not None and capital_employed is not None and capital_employed > 0
            else None
        ),
        "priceToEarnings": metric("peTTM", "peAnnual"),
        "earningsPerShare": metric("epsTTM", "epsAnnual"),
        "priceToSales": current_price / revenue_per_share if current_price and revenue_per_share else None,
        "priceToBook": current_price / book_value_per_share if current_price and book_value_per_share else None,
        "ebitda": annual_ebitda,
        "enterpriseValueToEbitda": metric("evEbitdaTTM", "evEbitdaAnnual"),
        "debtToEquity": metric("totalDebt/totalEquityQuarterly", "totalDebt/totalEquityAnnual"),
        "currentRatio": metric("currentRatioQuarterly", "currentRatioAnnual"),
        "quickRatio": metric("quickRatioQuarterly", "quickRatioAnnual"),
        "netDebt": net_debt,
        "freeCashFlow": free_cash_flow,
        "operatingCashFlow": operating_cash_flow,
        "revenueGrowthRate": metric("revenueGrowthTTMYoy", "revenueGrowthQuarterlyYoy"),
        "inventoryTurnover": metric("inventoryTurnoverTTM", "inventoryTurnoverAnnual"),
        "assetTurnover": metric("assetTurnoverTTM", "assetTurnoverAnnual"),
        "beta": metric("beta"),
        "dividendYield": metric("dividendYieldIndicatedAnnual"),
    }, {
        "balanceSheet": str(latest_balance.get("asOf", "")).split(" ")[0]
        if isinstance(latest_balance, dict) and latest_balance.get("asOf") else None,
        "annualStatements": str(annual.get("asOf", "")).split(" ")[0]
        if isinstance(annual, dict) and annual.get("asOf") else None,
        "ratioMetrics": "TTM; latest reported quarter where applicable",
    }


def build_profitability_history(statements: dict[str, Any] | None) -> list[dict[str, Any]]:
    """Calculate annual margins and returns from reported income and balance sheets."""
    statements = statements if isinstance(statements, dict) else {}
    annual_history = statements.get("annualHistory")
    if not isinstance(annual_history, list):
        return []

    def normalized_label(value: Any) -> str:
        return "".join(character for character in str(value).casefold() if character.isalnum())

    def statement_value(rows: Any, *labels: str) -> float | None:
        if not isinstance(rows, list):
            return None
        targets = {normalized_label(label) for label in labels}
        for row in rows:
            if isinstance(row, dict) and normalized_label(row.get("label")) in targets:
                value = row.get("value")
                if isinstance(value, (int, float)) and math.isfinite(value):
                    return float(value)
        return None

    history = []
    for report in annual_history:
        if not isinstance(report, dict):
            continue
        as_of = str(report.get("asOf") or "")[:10]
        income = report.get("incomeStatement")
        balance = report.get("balanceSheet")
        revenue = statement_value(
            income,
            "Net sales",
            "Revenue",
            "Total revenue",
            "Revenue from contract with customer excluding assessed tax",
        )
        gross_profit = statement_value(income, "Gross margin", "Gross profit")
        if gross_profit is None and revenue is not None:
            cost_of_sales = statement_value(income, "Cost of sales", "Cost of revenue")
            gross_profit = revenue - cost_of_sales if cost_of_sales is not None else None
        operating_income = statement_value(income, "Operating income", "Income from operations")
        net_income = statement_value(income, "Net income", "Net income loss")
        equity = statement_value(
            balance,
            "Total shareholders’ equity",
            "Total shareholders' equity",
            "Total stockholders’ equity",
            "Total stockholders' equity",
        )
        assets = statement_value(balance, "Total assets")
        current_liabilities = statement_value(balance, "Total current liabilities")

        if not as_of or not any(value is not None for value in (revenue, net_income, operating_income)):
            continue
        history.append({
            "period": as_of[:4],
            "asOf": as_of,
            "grossProfitMargin": round(gross_profit / revenue * 100, 2)
            if gross_profit is not None and revenue else None,
            "operatingProfitMargin": round(operating_income / revenue * 100, 2)
            if operating_income is not None and revenue else None,
            "netProfitMargin": round(net_income / revenue * 100, 2)
            if net_income is not None and revenue else None,
            "returnOnEquity": round(net_income / equity * 100, 2)
            if net_income is not None and equity else None,
            "returnOnAssets": round(net_income / assets * 100, 2)
            if net_income is not None and assets else None,
            "returnOnCapitalEmployed": round(operating_income / (assets - current_liabilities) * 100, 2)
            if operating_income is not None and assets is not None and current_liabilities is not None
            and assets > current_liabilities else None,
        })
    return history


def evaluate_sma_crossover(symbol: str, history: dict[str, Any]) -> dict[str, Any]:
    """Evaluate a long-only moving-average baseline; this function never places orders."""
    bars = history.get("data")
    bars = bars if isinstance(bars, list) else []
    event: dict[str, Any] = {
        "symbol": symbol,
        "strategy": STRATEGY_NAME,
        "strategyVersion": STRATEGY_VERSION,
        "status": "NOT_EVALUATED",
        "signal": None,
        "reason": None,
        "source": history.get("source"),
        "mock": history.get("mock"),
        "historyError": history.get("error"),
        "barsUsed": len(bars),
        "asOf": bars[-1].get("date") if bars and isinstance(bars[-1], dict) else None,
        "evaluatedAt": datetime.now(timezone.utc).isoformat(),
        "fastWindow": FAST_WINDOW,
        "slowWindow": SLOW_WINDOW,
    }

    if history.get("source") not in VERIFIED_HISTORY_SOURCES or history.get("mock") is not False:
        event["reason"] = "SOURCE_NOT_VERIFIED"
        return _finish_event(event)

    if len(bars) < SLOW_WINDOW + 1:
        event["reason"] = "INSUFFICIENT_HISTORY"
        return _finish_event(event)

    try:
        dates = [datetime.strptime(bar["date"], "%Y-%m-%d").date() for bar in bars]
        closes = [float(bar["close"]) for bar in bars]
    except (KeyError, TypeError, ValueError):
        event["reason"] = "INVALID_HISTORY_FORMAT"
        return _finish_event(event)

    if dates != sorted(set(dates)) or dates[-1] > date.today():
        event["reason"] = "INVALID_HISTORY_CHRONOLOGY"
        return _finish_event(event)

    if any(not math.isfinite(close) or close <= 0 for close in closes):
        event["reason"] = "INVALID_CLOSE_PRICE"
        return _finish_event(event)

    previous_fast = sum(closes[-FAST_WINDOW - 1:-1]) / FAST_WINDOW
    previous_slow = sum(closes[-SLOW_WINDOW - 1:-1]) / SLOW_WINDOW
    current_fast = sum(closes[-FAST_WINDOW:]) / FAST_WINDOW
    current_slow = sum(closes[-SLOW_WINDOW:]) / SLOW_WINDOW

    if previous_fast <= previous_slow and current_fast > current_slow:
        signal = "BUY"
        reason = "FAST_AVERAGE_CROSSED_ABOVE_SLOW_AVERAGE"
    elif previous_fast >= previous_slow and current_fast < current_slow:
        signal = "SELL"
        reason = "FAST_AVERAGE_CROSSED_BELOW_SLOW_AVERAGE"
    else:
        signal = "HOLD"
        reason = "NO_CROSSOVER"

    event.update({
        "status": "EVALUATED",
        "signal": signal,
        "reason": reason,
        "fastAverage": round(current_fast, 6),
        "slowAverage": round(current_slow, 6),
    })
    return _finish_event(event)


def analyze_stock_history(
    symbol: str,
    history: dict[str, Any],
    quote: dict[str, Any] | None = None,
    fundamentals: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Calculate descriptive technical metrics from verified daily candles."""
    bars = history.get("data")
    bars = bars if isinstance(bars, list) else []
    fundamentals = fundamentals if isinstance(fundamentals, dict) else {}
    financial_kpis, financial_kpi_periods = build_financial_kpis(
        fundamentals.get("metrics"),
        fundamentals.get("statements"),
        quote,
    )
    profitability_history = build_profitability_history(fundamentals.get("statements"))
    result: dict[str, Any] = {
        "symbol": symbol,
        "status": "NOT_EVALUATED",
        "reason": None,
        "source": history.get("source"),
        "mock": history.get("mock"),
        "barsUsed": len(bars),
        "asOf": bars[-1].get("date") if bars and isinstance(bars[-1], dict) else None,
        "evaluatedAt": datetime.now(timezone.utc).isoformat(),
        "quote": quote if isinstance(quote, dict) else None,
        "company": fundamentals.get("profile"),
        "fundamentals": fundamentals.get("metrics"),
        "financialKpis": financial_kpis,
        "financialKpiPeriods": financial_kpi_periods,
        "profitabilityHistory": profitability_history,
    }

    if history.get("source") not in VERIFIED_HISTORY_SOURCES or history.get("mock") is not False:
        result["reason"] = "SOURCE_NOT_VERIFIED"
        return result
    if len(bars) < SLOW_WINDOW + 1:
        result["reason"] = "INSUFFICIENT_HISTORY"
        return result

    try:
        dates = [datetime.strptime(bar["date"], "%Y-%m-%d").date() for bar in bars]
        closes = [float(bar["close"]) for bar in bars]
        volumes = [float(bar["volume"]) for bar in bars]
        highs = [float(bar["high"]) for bar in bars]
        lows = [float(bar["low"]) for bar in bars]
    except (KeyError, TypeError, ValueError):
        result["reason"] = "INVALID_HISTORY_FORMAT"
        return result

    if dates != sorted(set(dates)) or dates[-1] > date.today():
        result["reason"] = "INVALID_HISTORY_CHRONOLOGY"
        return result
    if any(
        not math.isfinite(value) or value < 0
        for series in (closes, volumes, highs, lows)
        for value in series
    ) or any(value == 0 for value in closes + highs + lows):
        result["reason"] = "INVALID_HISTORY_VALUES"
        return result

    def average(values: list[float], window: int) -> float | None:
        if len(values) < window:
            return None
        return sum(values[-window:]) / window

    def ema(values: list[float], window: int) -> list[float]:
        multiplier = 2 / (window + 1)
        output = [values[0]]
        for value in values[1:]:
            output.append((value - output[-1]) * multiplier + output[-1])
        return output

    daily_returns = [
        closes[index] / closes[index - 1] - 1
        for index in range(1, len(closes))
    ]
    recent_returns = daily_returns[-252:]
    volatility = None
    if len(recent_returns) > 1:
        mean_return = sum(recent_returns) / len(recent_returns)
        variance = sum((value - mean_return) ** 2 for value in recent_returns) / (len(recent_returns) - 1)
        volatility = math.sqrt(variance * 252) * 100

    gains = [max(value, 0) for value in daily_returns]
    losses = [max(-value, 0) for value in daily_returns]
    rsi = None
    if len(daily_returns) >= 14:
        average_gain = sum(gains[:14]) / 14
        average_loss = sum(losses[:14]) / 14
        for index in range(14, len(daily_returns)):
            average_gain = (average_gain * 13 + gains[index]) / 14
            average_loss = (average_loss * 13 + losses[index]) / 14
        rsi = 100.0 if average_loss == 0 else 100 - 100 / (1 + average_gain / average_loss)

    fast_ema = ema(closes, 12)
    slow_ema = ema(closes, 26)
    macd_values = [fast - slow for fast, slow in zip(fast_ema, slow_ema)]
    macd_signal_values = ema(macd_values, 9)
    macd_line = macd_values[-1]
    macd_signal = macd_signal_values[-1]

    moving_averages = {
        str(window): average(closes, window)
        for window in (20, 50, 200)
    }
    current_price = closes[-1]
    previous_fast = average(closes[:-1], FAST_WINDOW)
    previous_slow = average(closes[:-1], SLOW_WINDOW)
    current_fast = moving_averages[str(FAST_WINDOW)]
    current_slow = moving_averages[str(SLOW_WINDOW)]
    if previous_fast is not None and previous_slow is not None and previous_fast <= previous_slow and current_fast > current_slow:
        crossover = "BULLISH_CROSSOVER"
    elif previous_fast is not None and previous_slow is not None and previous_fast >= previous_slow and current_fast < current_slow:
        crossover = "BEARISH_CROSSOVER"
    else:
        crossover = "NO_CROSSOVER"

    if current_price > current_slow and current_fast > current_slow:
        bias = "BULLISH"
    elif current_price < current_slow and current_fast < current_slow:
        bias = "BEARISH"
    else:
        bias = "MIXED"

    periods = {"1W": 5, "1M": 21, "3M": 63, "6M": 126, "1Y": 252}
    performance = {
        label: round((current_price / closes[-bars_ago - 1] - 1) * 100, 2)
        if len(closes) > bars_ago else None
        for label, bars_ago in periods.items()
    }
    peak = closes[0]
    max_drawdown = 0.0
    for close in closes:
        peak = max(peak, close)
        max_drawdown = min(max_drawdown, (close / peak - 1) * 100)

    average_volume = average(volumes, 20)
    chart_history = []
    for index, bar in enumerate(bars):
        chart_row = {"date": bar["date"], "close": closes[index]}
        for window in (20, 50, 200):
            chart_row[f"sma{window}"] = average(closes[:index + 1], window)
        chart_history.append(chart_row)

    result.update({
        "status": "EVALUATED",
        "price": round(current_price, 4),
        "performancePct": performance,
        "trend": {
            "bias": bias,
            "movingAverages": {
                key: round(value, 4) if value is not None else None
                for key, value in moving_averages.items()
            },
            "priceVsSma20Pct": round((current_price / moving_averages["20"] - 1) * 100, 2),
            "priceVsSma50Pct": round((current_price / moving_averages["50"] - 1) * 100, 2),
            "priceVsSma200Pct": round((current_price / moving_averages["200"] - 1) * 100, 2)
            if moving_averages["200"] is not None else None,
            "crossover": crossover,
        },
        "momentum": {
            "rsi14": round(rsi, 2) if rsi is not None else None,
            "rsiState": "OVERBOUGHT" if rsi is not None and rsi >= 70
            else "OVERSOLD" if rsi is not None and rsi <= 30
            else "NEUTRAL" if rsi is not None else None,
            "macd": round(macd_line, 4),
            "macdSignal": round(macd_signal, 4),
            "macdHistogram": round(macd_line - macd_signal, 4),
        },
        "risk": {
            "annualizedVolatilityPct": round(volatility, 2) if volatility is not None else None,
            "maxDrawdownPct": round(max_drawdown, 2),
            "high52Week": round(max(highs[-252:]), 4),
            "low52Week": round(min(lows[-252:]), 4),
            "averageVolume20": round(average_volume) if average_volume is not None else None,
            "latestVolume": round(volumes[-1]),
            "volumeVsAverage20Pct": round((volumes[-1] / average_volume - 1) * 100, 2)
            if average_volume else None,
        },
        "priceHistory": chart_history[-252:],
    })
    return _finish_event(result)